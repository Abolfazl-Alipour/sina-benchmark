"""AnyBURL rule-mining wrapper (spec §6.3).

Exports training/test triples, generates AnyBURL config files, runs the pinned
jar, and parses prediction rankings into a long-format score table. The
confidence values are left as-is; empirical-CDF rank normalization happens
downstream in the ensemble scorer.
"""

import subprocess
from pathlib import Path

import polars as pl


def export_triples(edges: pl.DataFrame, path: Path) -> None:
    """Write AnyBURL triple format: head<TAB>relation<TAB>tail per line.

    Relation names are sanitized for AnyBURL's Atom parser (spaces → '_').
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    out = edges.with_columns(pl.col("relation").str.replace_all(" ", "_")).select(
        "src_id", "relation", "dst_id"
    )
    out.write_csv(path, separator="\t", include_header=False)


def write_learn_config(
    path: Path,
    train_path: Path,
    output_dir: Path,
    worker_threads: int = 4,
    snapshots_at: str = "10,50,100",
) -> None:
    """Generate config-learn.properties for the AnyBURL Learn class."""
    text = f"""# Auto-generated by sina.anyburl
PATH_TRAINING = {train_path}
PATH_OUTPUT = {output_dir / "rules"}
WORKER_THREADS = {worker_threads}
SNAPSHOTS_AT = {snapshots_at}
"""
    path.write_text(text, encoding="utf-8")


def write_apply_config(
    path: Path,
    rules_path: Path,
    train_path: Path,
    test_path: Path,
    output_file: Path,
    valid_path: Path | None = None,
    worker_threads: int = 4,
    top_k: int = 10,
) -> None:
    """Generate config-apply.properties for the AnyBURL Apply class."""
    valid_line = f"PATH_VALID = {valid_path}\n" if valid_path else ""
    text = f"""# Auto-generated by sina.anyburl
PATH_RULES = {rules_path}
PATH_TRAINING = {train_path}
PATH_TEST = {test_path}
{valid_line}PATH_OUTPUT = {output_file}
WORKER_THREADS = {worker_threads}
TOP_K_OUTPUT = {top_k}
"""
    path.write_text(text, encoding="utf-8")


def run_anyburl(
    jar_path: Path,
    java_class: str,
    config_path: Path,
    max_heap_gb: int = 8,
    timeout_s: int = 3600,
) -> subprocess.CompletedProcess[str]:
    """Run an AnyBURL class and return the completed process."""
    cmd = [
        "java",
        f"-Xmx{max_heap_gb}G",
        "-cp",
        str(jar_path),
        f"de.unima.ki.anyburl.{java_class}",
        str(config_path),
    ]
    return subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=timeout_s,
        check=False,
    )


def filter_rules(rules_in: Path, rules_out: Path) -> int:
    """Drop malformed rules with an empty body (AnyBURL edge-case output).

    Returns the number of rules kept.
    """
    kept = 0
    with rules_in.open("r", encoding="utf-8") as src, rules_out.open("w", encoding="utf-8") as dst:
        for line in src:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 4:
                continue
            rule = parts[3]
            if rule.rstrip().endswith("<="):
                continue
            dst.write(line)
            kept += 1
    return kept


def parse_predictions(path: Path, prediction_type: str = "tails") -> pl.DataFrame:
    """Parse AnyBURL prediction output into (query_id, candidate_id, score).

    AnyBURL writes one test triple, then a "Heads:" line, then a "Tails:" line
    containing candidate-score pairs separated by whitespace. `prediction_type`
    selects which side to extract; the query is the *other* side of the triple.
    """
    if prediction_type not in {"heads", "tails"}:
        raise ValueError(f"prediction_type must be 'heads' or 'tails', got {prediction_type}")
    target = "Heads:" if prediction_type == "heads" else "Tails:"
    rows: list[tuple[str, str, float]] = []
    with path.open("r", encoding="utf-8") as fh:
        lines = [line.rstrip("\n") for line in fh]
    i = 0
    while i < len(lines):
        parts = lines[i].split()
        if len(parts) < 3:
            i += 1
            continue
        query = parts[0] if prediction_type == "tails" else parts[2]
        # find the target line
        j = i + 1
        while j < len(lines) and not lines[j].startswith(target):
            j += 1
        if j < len(lines):
            pred_line = lines[j][len(target) :].strip()
            if pred_line:
                tokens = pred_line.split()
                for k in range(0, len(tokens) - 1, 2):
                    cand, score_str = tokens[k], tokens[k + 1]
                    try:
                        score = float(score_str)
                    except ValueError:
                        continue
                    rows.append((query, cand, score))
        i = j + 1 if j < len(lines) else i + 1
    return pl.DataFrame(
        {
            "query_id": [r[0] for r in rows],
            "candidate_id": [r[1] for r in rows],
            "score": [r[2] for r in rows],
        },
        schema={"query_id": pl.String, "candidate_id": pl.String, "score": pl.Float64},
    )
